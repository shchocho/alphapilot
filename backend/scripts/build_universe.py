def main() -> None:
    provider = NaverProvider()
    today = pd.Timestamp.now(tz="Asia/Seoul").normalize().tz_localize(None)
    kept: list[tuple[str, str, str, str]] = []
    dropped: list[str] = []
    for code, market, sector, memo in CANDIDATES:
        try:
            name, bars = provider.fetch(code, 30)
        except Exception as exc:  # noqa: BLE001
            dropped.append(f"{code} {memo}: 조회 실패 ({exc})")
            continue
        if bars.empty or (today - bars.index[-1]).days > STALE_DAYS:
            dropped.append(f"{code} {memo}: 최근 봉 없음")
            continue
        avg_value = float((bars["close"] * bars["volume"]).tail(20).mean())
        if avg_value < MIN_AVG_VALUE:
            dropped.append(f"{code} {name}: 평균 거래대금 {avg_value / 1e8:.0f}억 미달")
            continue
        if name.replace(" ", "") != memo.replace(" ", ""):
            print(f"  이름 차이: {code} 메모='{memo}' 실제='{name}'")
        kept.append((code, name or memo, market, sector))

    out = Path(__file__).resolve().parents[1] / "app" / "data" / "universe.csv"
    with out.open("w", encoding="utf-8", newline="") as fh:
        writer = csv.writer(fh)
        writer.writerow(["code", "name", "market", "sector"])
        writer.writerows(kept)
    print(f"유지 {len(kept)}종목 → {out}")
    for line in dropped:
        print("  제외:", line)


if __name__ == "__main__":
    main()
